export const dictionaries: Record<Language, Dictionary> = { en, hi, te };

export function getDictionary(language: Language | null | undefined): Dictionary {
  return dictionaries[language ?? "en"] ?? en;
}

/** BCP 47 locale for dates and times, e.g. weekday and month names. */
export const LOCALES: Record<Language, string> = { en: "en-IN", hi: "hi-IN", te: "te-IN" };

/** Which `today.greet*` to use, by the hour in India. */
export function greetingKey(hour: number): "greetMorning" | "greetAfternoon" | "greetEvening" {
  if (hour < 12) return "greetMorning";
  if (hour < 17) return "greetAfternoon";
  return "greetEvening";
}

